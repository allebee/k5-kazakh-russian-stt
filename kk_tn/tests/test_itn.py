import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from kk_tn.itn import inverse_normalize as itn  # noqa: E402


@pytest.mark.parametrize("spoken,written", [
    ("екі мың жиырма төртінші жылы", "2024 жылы"),
    ("мың бес жүз теңге", "1500 теңге"),
    ("елу мың теңгеге", "50 000 теңгеге"),
    ("бір жарым миллион теңге", "1,5 млн теңге"),
    ("екі бүтін жүзден жетпіс бес", "2,75"),
    ("он бесінші наурыз", "15 наурыз"),
    ("наурыздың он бесі", "наурыздың 15-і"),
    ("үшінші сыныпқа", "3-сыныпқа"),
    ("бесінші орын", "5-орын"),
    ("жиырма бірінші ғасыр", "21-ғасыр"),
    ("қырқыншы жылдары", "40-жылдары"),
    ("бір мың тоғыз жүз жетпіс жетінші – сексен бірінші жылдары", "1977–1981 жылдары"),
    ("жиырма бес пайызға", "25%-ға"),
    ("сегіз жеті жүз жетпіс жеті нөл нөл нөл он бір жиырма екі", "8 777 000 11 22"),
    ("плюс жеті жеті жүз бір бір жүз жиырма үш қырық бес алпыс жеті", "+7 701 123 45 67"),
    ("сағат он бес отызда", "сағат 15:30-да"),
    ("сағат тоғыз нөл бесте", "сағат 9:05-те"),
    ("төрт мыңдай адам", "4000-дай адам"),
    ("жүзден астам адам", "100-ден астам адам"),
    ("пять тысяч теңге", "5000 теңге"),
    # non-standard spellings are read like the standard ones (TN writes қырқыншы)
    ("бір мың тоғыз жүз қырықыншы жылы", "1940 жылы"),
    ("бір мың тоғыз жүз қырқыншы жылы", "1940 жылы"),
    ("жиырманшы ғасыр", "20-ғасыр"),
    ("қырқына дейін", "40-ына дейін"),
    ("қырықына дейін", "40-ына дейін"),
    # short segments without әғқңөұүһі: an unambiguous Kazakh number word enables Kazakh reading
    ("отыз бес", "35"),
    ("алпысыншы жылдары", "60-жылдары"),
])
def test_itn(spoken, written):
    assert itn(spoken) == written


@pytest.mark.parametrize("text", [
    "бір күні", "бір адам келді", "екеуміз", "біріншіден", "мыңдаған адам", "бірінші рет",
    "онда отыз", "оны көрдім", "бірге барайық", "один из нас",
])
def test_itn_keeps_words(text):
    out = itn(text)
    assert out.split()[0] == text.split()[0]


@pytest.mark.parametrize("text", [
    "он бес",                     # "он"/"бес" are also Russian: guarded without another Kazakh cue
    "он сказал, что придёт",
])
def test_itn_russian_guard(text):
    assert itn(text) == text
