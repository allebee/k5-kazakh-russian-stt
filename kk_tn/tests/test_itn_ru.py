import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from kk_tn.itn import inverse_normalize as itn  # noqa: E402


@pytest.mark.parametrize("spoken,written", [
    ("в две тысячи двадцать четвёртом году", "в 2024 году"),
    ("в тысяча девятьсот девяносто первом году", "в 1991 году"),
    ("пятнадцатого марта две тысячи двадцать четвёртого года", "15 марта 2024 года"),
    ("к первому сентября", "к 1 сентября"),
    ("тысяча пятьсот рублей", "1500 рублей"),
    ("полторы тысячи рублей", "1500 рублей"),
    ("пятьдесят тысяч тенге", "50 000 тенге"),
    ("два миллиона долларов", "2 млн долларов"),
    ("два с половиной миллиона", "2,5 млн"),
    ("полтора миллиона тенге", "1,5 млн тенге"),
    ("три целых семь десятых процента", "3,7%"),
    ("двадцать пять процентов", "25%"),
    ("одна целая пять десятых", "1,5"),
    ("ноль целых двадцать пять сотых", "0,25"),
    ("полтора часа", "1,5 часа"),
    ("в четырнадцать тридцать", "в 14:30"),
    ("в девять часов пятнадцать минут", "в 9:15"),
    ("в пять часов", "в 5 часов"),
    ("восемь семьсот семьдесят семь ноль ноль ноль одиннадцать двадцать два", "8 777 000 11 22"),
    ("плюс семь семьсот один сто двадцать три сорок пять шестьдесят семь", "+7 701 123 45 67"),
    ("второй этаж", "2-й этаж"),
    ("на третьем этаже", "на 3-м этаже"),
    ("в пятом классе", "в 5-м классе"),
    ("на двадцать пятом месте", "на 25-м месте"),
    ("сорок второй раз", "42-й раз"),
    ("в двадцать первом веке", "в XXI веке"),
    ("около ста человек", "около 100 человек"),
    ("сто двадцать три тысячи", "123 000"),
    ("мне двадцать два года", "мне 22 года"),
    ("пять килограммов", "5 килограммов"),
    ("двадцати пяти рублей", "25 рублей"),
])
def test_itn_ru(spoken, written):
    assert itn(spoken) == written


@pytest.mark.parametrize("text", [
    "у меня один брат", "один из нас", "первый раз", "одно и то же", "она одна дома",
    "ни одного", "второй вариант лучше", "три дня назад",
])
def test_itn_ru_keeps_words(text):
    assert itn(text) == text
